def manifest(namespace):
    tokens = []
    for name, value in T.color_vars():
        tokens.append({"name": name, "value": value, "kind": "color", "definedIn": "colors_and_type.css"})
    for name, value, _note in T.SEMANTIC:
        kind = "font" if name.startswith("--fg") else "color"
        tokens.append({"name": name, "value": value, "kind": kind, "definedIn": "colors_and_type.css"})
    tokens.append({"name": "--font-sans", "value": T.FONT_STACK, "kind": "font", "definedIn": "colors_and_type.css"})
    tokens.append({"name": "--font-mono", "value": T.MONO_STACK, "kind": "font", "definedIn": "colors_and_type.css"})
    for role, px, _uses, _note in T.TYPE:
        tokens.append({"name": f"--type-{role}", "value": f"{px}px", "kind": "font", "definedIn": "colors_and_type.css"})
    for role, weight, _uses, _note in T.TYPE_WEIGHTS:
        tokens.append({"name": f"--weight-{role}", "value": str(weight), "kind": "font", "definedIn": "colors_and_type.css"})
    for role, value, _note in T.TYPE_TRACKING:
        tokens.append({"name": f"--tracking-{role}", "value": value, "kind": "font", "definedIn": "colors_and_type.css"})
    for step, px in T.SPACING:
        tokens.append({"name": f"--space-{str(step).replace('.', '_')}", "value": f"{px}px", "kind": "spacing", "definedIn": "colors_and_type.css"})
    for name, value, _note in T.RADII:
        tokens.append({"name": f"--radius-{name}", "value": value, "kind": "radius", "definedIn": "colors_and_type.css"})
    return {
        "namespace": namespace,
        "components": [],
        "startingPoints": [],
        "cards": CARDS,
        "templates": [],
        "hasThumbnailHtml": False,
        "globalCssPaths": ["colors_and_type.css"],
        "tokens": tokens,
        "themes": [],
        "fonts": [],
        "brandFonts": [{"family": "System sans", "status": "ok", "tokens": ["--font-sans"], "path": "colors_and_type.css"}],
        "source": "spa",
    }


def build(namespace="OathcraftDesignSystem"):
    colour_cards()
    type_cards()
    spacing_cards()
    plate_cards()
    component_cards()
    party_cards()
    status_card()
    motion_card()
    write("colors_and_type.css", stylesheet())
    write("_ds_manifest.json", json.dumps(manifest(namespace), indent=2) + "\n")
    print(f"wrote {len(CARDS)} cards + colors_and_type.css + _ds_manifest.json")
    return CARDS


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "OathcraftDesignSystem")
