# --- Card shell ------------------------------------------------------------
def card(path, group, name, subtitle, body, extra_css="", width=560):
    """One preview card. The @dsCard marker MUST be the first line — the pane
    builds its index from it."""
    CARDS.append({"path": f"preview/{path}", "group": group, "subtitle": subtitle, "name": name})
    html = f"""<!-- @dsCard group="{group}" name="{name}" subtitle="{subtitle}" -->
<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <link rel="stylesheet" href="../colors_and_type.css" />
    <style>
      .ds-card {{ width: {width}px; }}
      {extra_css}
    </style>
  </head>
  <body>
    <div class="ds-card">{body}</div>
  </body>
</html>
"""
    write(os.path.join("preview", path), html)


def write(rel, text):
    full = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as handle:
        handle.write(text)


